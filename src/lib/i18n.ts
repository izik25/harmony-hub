/**
 * Country → default language mapping (TikTok-style: detect region, pick language).
 * Overridden by explicit user selection (persisted in localStorage).
 */
const countryToLang: Record<string, string> = {
  IL: "he",
  SA: "ar",
  AE: "ar",
  EG: "ar",
  JO: "ar",
  LB: "ar",
  SY: "ar",
  IQ: "ar",
  KW: "ar",
  QA: "ar",
  BH: "ar",
  OM: "ar",
  YE: "ar",
  PS: "ar",
  MA: "ar",
  DZ: "ar",
  TN: "ar",
  LY: "ar",
  SD: "ar",
};

function guessFromLanguageTags(tags: Array<string>): string {
  for (const l of tags) {
    const lower = l.toLowerCase();
    if (lower.startsWith("he") || lower.startsWith("iw")) return "he";
    if (lower.startsWith("ar")) return "ar";
    const region = lower.split("-")[1]?.toUpperCase();
    if (region && countryToLang[region]) return countryToLang[region];
  }
  return "en";
}

function guessFromLocale(): string {
  if (typeof navigator === "undefined") return "en";
  return guessFromLanguageTags(
    navigator.languages ? [...navigator.languages] : [navigator.language],
  );
}

/**
 * Mirrors guessFromLocale() but for the server, where there's no `navigator`.
 * Keeps the very first SSR paint in the same language the client will hydrate
 * to for a fresh visitor (no stored preference yet), avoiding a hydration
 * mismatch / language flash. Parses a raw `Accept-Language` header value
 * (e.g. "he-IL,he;q=0.9,en;q=0.8").
 */
export function guessFromAcceptLanguageHeader(header: string | undefined | null): string {
  if (!header) return "en";
  const tags = header
    .split(",")
    .map((part) => part.split(";")[0]?.trim())
    .filter((tag): tag is string => !!tag);
  return guessFromLanguageTags(tags);
}

if (!i18n.isInitialized) {
  i18n
    .use(LanguageDetector)
    .use(initReactI18next)
    .init({
      resources: {
        en: { translation: en },
        he: { translation: he },
        ar: { translation: ar },
      },
      fallbackLng: "en",
      supportedLngs: ["en", "he", "ar"],
      // The client's very first render must hydrate against whatever the server actually
      // rendered, not an independent guess — Accept-Language (server) and navigator.language
      // (client) are two separate browser-maintained signals that can legitimately disagree
      // (e.g. a browser that sends no Accept-Language header at all while navigator.language
      // still reflects the OS locale). Guessing independently here caused React hydration
      // errors. `document.documentElement.lang` is the SSR HTML's own `<html lang>` attribute,
      // already parsed into the DOM before this module runs, so reading it back guarantees
      // agreement. Any correction toward the visitor's real preference happens afterwards, as
      // a normal post-mount state update (see reconcileClientLanguage below) instead of during
      // hydration.
      lng:
        typeof window !== "undefined"
          ? document.documentElement.lang || localStorage.getItem("lang") || guessFromLocale()
          : "en",
      interpolation: { escapeValue: false },
      detection: {
        order: ["localStorage", "navigator"],
        caches: ["localStorage"],
        lookupLocalStorage: "lang",
      },
    });
}

export const rtlLangs = new Set(["he", "ar"]);
export function isRTL(lng: string) {
  return rtlLangs.has(lng);
}

export function setLanguage(lng: string) {
  i18n.changeLanguage(lng);
  if (typeof window !== "undefined") {
    localStorage.setItem("lang", lng);
    // Also mirrored into a cookie (not just localStorage) so the server can render
    // the right language on the very first SSR pass instead of flashing English.
    document.cookie = `lang=${lng}; path=/; max-age=${60 * 60 * 24 * 365}; samesite=lax`;
    document.documentElement.lang = lng;
    document.documentElement.dir = isRTL(lng) ? "rtl" : "ltr";
  }
}

/**
 * Runs once after the client mounts. A fresh visitor (no saved preference yet) hydrates in
 * whatever language the server guessed from the Accept-Language header, which may not match
 * their actual browser/OS locale (see the `lng` comment above). This nudges them to their real
 * language right after hydration — a normal reactive update, not a hydration-time change — and
 * persists it so every subsequent request (including SSR) gets it right immediately.
 */
export function reconcileClientLanguage() {
  if (typeof window === "undefined") return;
  if (localStorage.getItem("lang")) return;
  const guessed = guessFromLocale();
  if (guessed !== i18n.language) setLanguage(guessed);
}

/**
 * Server functions throw plain error codes (e.g. "handleTaken") so they stay
 * translatable on the client without the server needing to know the viewer's
 * locale. Falls back to the raw message for anything not in the map — including
 * errors that were already translated client-side before being thrown.
 */
export function translateServerError(message: string): string {
  return i18n.t(`serverError.${message}`, { defaultValue: message });
}

